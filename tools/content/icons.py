"""Bake small vector symbols into coverage masks; no runtime rasterizer needed.

Run from the repository root: python -m tools.content.icons
Coordinates describe pixel edges. All status symbols share an 11 x 11 cell.
"""
from pathlib import Path
import math


def stroke(points, width=1.35):
    def inside(x, y):
        for (ax, ay), (bx, by) in zip(points, points[1:]):
            dx, dy = bx-ax, by-ay
            t = max(0, min(1, ((x-ax)*dx+(y-ay)*dy)/(dx*dx+dy*dy)))
            if (x-ax-t*dx)**2+(y-ay-t*dy)**2 <= (width/2)**2:
                return True
        return False
    return inside


def polygon(points):
    def inside(x, y):
        result = False
        for (ax, ay), (bx, by) in zip(points, points[1:]+points[:1]):
            if (ay > y) != (by > y) and x < (bx-ax)*(y-ay)/(by-ay)+ax:
                result = not result
        return result
    return inside


def rounded(x0, y0, x1, y1, radius):
    def inside(x, y):
        dx = max(x0+radius-x, 0, x-(x1-radius))
        dy = max(y0+radius-y, 0, y-(y1-radius))
        return x0 <= x <= x1 and y0 <= y <= y1 and dx*dx+dy*dy <= radius*radius
    return inside


def union(*shapes):
    return lambda x, y: any(s(x, y) for s in shapes)


def ring(outer, inner):
    return lambda x, y: outer(x, y) and not inner(x, y)


def arc(cx, cy, radius, start, end):
    return [(cx+radius*math.cos(start+(end-start)*i/32),
             cy+radius*math.sin(start+(end-start)*i/32)) for i in range(33)]


def generate():
    shapes = {
        'play': (11, 11, polygon([(2.5, 1), (9.5, 5.5), (2.5, 10)])),
        'pause': (11, 11, union(rounded(2, 1, 4.25, 10, .65), rounded(6.75, 1, 9, 10, .65))),
        'headphones': (11, 11, union(stroke(arc(5.5, 5.2, 4, math.pi, 2*math.pi)),
            stroke([(1.5, 5.2), (1.5, 8)]), stroke([(9.5, 5.2), (9.5, 8)]),
            rounded(1, 6, 3.4, 10, .8), rounded(7.6, 6, 10, 10, .8))),
        'lock': (11, 11, union(stroke(arc(5.5, 3.5, 2.5, math.pi, 2*math.pi)),
            stroke([(3, 3.5), (3, 5.5)]), stroke([(8, 3.5), (8, 5.5)]),
            ring(rounded(1, 4.5, 10, 10.5, 1.2), rounded(4.9, 6.3, 6.1, 8.8, .55)))),
        'clock': (11, 11, union(stroke(arc(5.5, 5.5, 4.5, 0, 2*math.pi), 1.1),
            stroke([(5.5, 2.6), (5.5, 5.5), (7.8, 6.6)], 1.1))),
        'repeat': (15, 11, union(stroke([(1.5,5),(1.5,3),(3,1.5),(11,1.5)],1.2),
            polygon([(10,0),(13,1.5),(10,3)]),
            stroke([(13.5,5),(13.5,8),(12,9.5),(4,9.5)],1.2),
            polygon([(4,8),(1,9.5),(4,11)]))),
        'shuffle': (15, 11, union(stroke([(1,2),(3,2),(11,9),(13,9)],1.2),
            stroke([(1,9),(3,9),(11,2),(13,2)],1.2),
            polygon([(11.5,0),(14.5,2),(11.5,4)]),
            polygon([(11.5,7),(14.5,9),(11.5,11)]))),
        'chevron': (11, 11, stroke([(4, 2.5), (7, 5.5), (4, 8.5)])),
        'check': (11, 11, stroke([(1.8, 5.5), (4.3, 8), (9.2, 2.6)])),
        # Keep the charging mark inside the battery's inset, clear of its rim.
        'bolt': (11, 11, polygon([(6, 2), (3, 6), (5, 6), (4.5, 9), (8, 4.5), (6, 4.5)])),
        'battery': (25, 11, union(ring(rounded(0, 0, 23, 11, 1.6), rounded(1, 1, 22, 10, .8)), rounded(23, 3, 25, 8, .7))),
        'battery_vertical': (11, 25, union(ring(rounded(0, 2, 11, 25, 1.6), rounded(1, 3, 10, 24, .8)), rounded(3, 0, 8, 2, .7))),
    }
    lines = ['/* Generated by python -m tools.content.icons. 4-bit coverage. */']
    for name, (w, h, shape) in shapes.items():
        samples = [sum(shape(x+(sx+.5)/8, y+(sy+.5)/8)
                       for sy in range(8) for sx in range(8))
                   for y in range(h) for x in range(w)]
        alpha = [(n*15+32)//64 for n in samples]
        if len(alpha) % 2:
            alpha.append(0)
        packed = [(a << 4) | b for a, b in zip(alpha[::2], alpha[1::2])]
        lines.append(f'static const uint8_t symbol_{name}[] = {{')
        lines.extend('    '+','.join(f'0x{v:02x}' for v in packed[i:i+16])+',' for i in range(0, len(packed), 16))
        lines.append('};')
    Path('ui/runtime/symbols.h').write_text('\n'.join(lines)+'\n')


if __name__ == '__main__':
    generate()
